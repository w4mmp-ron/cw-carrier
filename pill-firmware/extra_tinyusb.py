# TinyUSB 0.21.0 sources + release date header + versioned release images (Ron 2026-11-11):
#   release/BlackPill-25MHz-<major>.<minor>-app.bin       app at 0x08008000
#   release/BlackPill-25MHz-<major>.<minor>-boot-app.bin  bootload-PA8.bin + app at 0x08000000
# Same rule as the PSoC copy-release.py: a version is never silently overwritten. If that
# version's file exists with different contents, the build is saved as ...-<ver>-b2-... and
# you are told to bump FIRMWARE_VERSION_MINOR. (build_info.h holds the build time, so every
# rebuild differs: bump the minor for every build you flash or ship.)
Import("env")
from datetime import datetime
from pathlib import Path
import re
import shutil

root = Path(env["PROJECT_DIR"])
tusb = root / "third_party_tinyusb" / "src"
inc = root / "include"
inc.mkdir(exist_ok=True)

now = datetime.now()
date_s = now.strftime("%Y-%m-%d")
datetime_s = now.strftime("%Y-%m-%d %H:%M:%S")
is_bench = env["PIOENV"] != "blackpill_f411ce"


def _fw_version() -> str:
    cfg = (inc / "proficio_config.h").read_text(encoding="utf-8", errors="ignore")
    maj = re.search(r"^#define\s+FIRMWARE_VERSION_MAJOR\s+(\d+)", cfg, re.M)
    mnr = re.search(r"^#define\s+FIRMWARE_VERSION_MINOR\s+(\d+)", cfg, re.M)
    if not (maj and mnr):
        raise SystemExit("extra_tinyusb.py: FIRMWARE_VERSION_MAJOR / MINOR not found in proficio_config.h")
    return f"{maj.group(1)}.{mnr.group(1)}"


FW_VERSION = _fw_version()
FW_PREFIX = f"BlackPill-25MHz-{FW_VERSION}"
app_name = f"{FW_PREFIX}-bench-app.bin" if is_bench else f"{FW_PREFIX}-app.bin"
combined_name = f"{FW_PREFIX}-boot-app.bin"
BOOTLOADER_BIN = "bootload-PA8.bin"  # in release/, flashed at 0x08000000
APP_OFFSET = 0x8000                  # app at 0x08008000

(build_hdr := inc / "build_info.h").write_text(
    "/* Auto-generated by extra_tinyusb.py — do not edit. */\n"
    "#ifndef PROFICIO_BUILD_INFO_H\n"
    "#define PROFICIO_BUILD_INFO_H\n"
    f'#define PROFICIO_FW_RELEASE_DATE     "{date_s}"\n'
    f'#define PROFICIO_FW_RELEASE_DATETIME "{datetime_s}"\n'
    f'#define PROFICIO_FW_BIN_NAME         "{app_name}"\n'
    "#endif\n",
    encoding="utf-8",
)
print(f"build_info.h: release {datetime_s}, version {FW_VERSION}")

env.Append(CPPPATH=[str(tusb)])

env.BuildSources(
    str(Path(env["BUILD_DIR"]) / "tinyusb"),
    str(tusb),
    src_filter=[
        "+<tusb.c>",
        "+<common/tusb_fifo.c>",
        "+<device/usbd.c>",
        "+<class/vendor/vendor_device.c>",
        "+<class/audio/audio_device.c>",
        "+<portable/synopsys/dwc2/dcd_dwc2.c>",
        "+<portable/synopsys/dwc2/dwc2_common.c>",
    ],
)


def _write_versioned(path: Path, data: bytes) -> Path:
    """Write data to path; never overwrite a different file of the same version (-b2, -b3...)."""
    if path.is_file() and path.read_bytes() == data:
        return path
    if path.is_file():
        stem = path.name.replace(f"{FW_PREFIX}-", f"{FW_PREFIX}-b{{n}}-", 1)
        n = 2
        while (path.parent / stem.format(n=n)).is_file() and (path.parent / stem.format(n=n)).read_bytes() != data:
            n += 1
        path = path.parent / stem.format(n=n)
        print(f"*** {FW_VERSION} already released with different contents: saved as {path.name}.")
        print("*** Bump FIRMWARE_VERSION_MINOR in include/proficio_config.h before you flash or ship it.")
    path.write_bytes(data)
    return path


def _copy_release_firmware(source, target, env):
    """After firmware.bin: release/BlackPill-25MHz-<ver>-app.bin (0x08008000) and, for the
    normal build, release/BlackPill-25MHz-<ver>-boot-app.bin = bootloader + 0xFF pad + app
    (0x08000000)."""
    src_bin = Path(env.subst("$BUILD_DIR")) / f"{env.subst('$PROGNAME')}.bin"
    if not src_bin.is_file():
        print(f"release firmware: missing {src_bin}")
        return

    # cw-carrier repo: pill-firmware/release/ (inside this repo; the original wrote to the
    # tree-level …/proficio-stm32f411-25MHz/release/, two folders up)
    rel = root / "release"
    rel.mkdir(exist_ok=True)

    rel_app = _write_versioned(rel / app_name, src_bin.read_bytes())
    print(f"app firmware (@ 0x08008000): {rel_app}")

    if is_bench:
        return  # bench build is for a bare Black Pill; no combined image
    bl_path = rel / BOOTLOADER_BIN
    if not bl_path.is_file():
        print(f"combined firmware: missing {bl_path}, skipped")
        return
    bl = bl_path.read_bytes()
    if len(bl) > APP_OFFSET:
        print(f"combined firmware: {BOOTLOADER_BIN} is {len(bl)} bytes (> {APP_OFFSET}), skipped")
        return
    combined = bl + b"\xff" * (APP_OFFSET - len(bl)) + src_bin.read_bytes()
    rel_combined = _write_versioned(rel / combined_name, combined)
    print(f"combined firmware (@ 0x08000000, {BOOTLOADER_BIN} + app): {rel_combined}")


env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", _copy_release_firmware)
